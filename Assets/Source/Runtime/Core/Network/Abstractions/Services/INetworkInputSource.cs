namespace Core.Network.Abstractions.Services
{
    /// <summary>
    /// Управление вводом активной сессии.
    /// </summary>
    /// <remarks>
    /// Регистрации коллектора здесь намеренно нет. Транспорту нужна структура ввода с
    /// ограничениями конкретной сетевой библиотеки, которые порт назвать не может, — попытка
    /// выразить их через <c>struct</c> вынуждала бы реализацию строить тип рефлексией, а это
    /// ломается на AOT. Коллектор подключает инсталлятор адаптера, где конкретные типы известны.
    /// </remarks>
    public interface INetworkInputSource
    {
        /// <summary>
        /// Когда ввод игрока не доехал, state authority переприменяет последний известный.
        /// Отключи, если игре нужен явный «пустой» ввод вместо повтора.
        /// </summary>
        bool RepeatLastInputOnMissing { get; set; }

        void Unregister<TInput>() where TInput : struct;
    }
}
