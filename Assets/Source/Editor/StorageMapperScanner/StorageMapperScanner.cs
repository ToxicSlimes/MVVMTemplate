#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Core.Abstractions.Services.GameData;
using UnityEditor;
using UnityEngine;

namespace Core.Editor.StorageMapperScanner
{
    public static class StorageMapperScanner
    {
        private const string OutputPath = "Assets/Source/Runtime/Core/CompositionRoot/Generated/StorageMapperRegistration.generated.cs";
        private const string Namespace = "Core.DependencyInjection.Generated";

        [MenuItem("Tools/GameData/Scan and Generate Storage Mapper Registration")]
        public static void ScanAndGenerate()
        {
            if (Generate())
                AssetDatabase.Refresh();
        }

        public static bool Generate()
        {
            var mappers = DiscoverMappers();

            if (mappers.Count == 0)
            {
                Debug.Log("[StorageMapperScanner] No IStorageMapper<T> implementations found.");
            }

            var code = GenerateRegistrationCode(mappers);

            EnsureDirectoryExists(Path.GetDirectoryName(OutputPath));

            if (!WriteIfChanged(OutputPath, code))
            {
                Debug.Log("[StorageMapperScanner] No changes detected, skipping.");
                return false;
            }

            Debug.Log($"[StorageMapperScanner] Generated {mappers.Count} mapper registrations at {OutputPath}");
            return true;
        }

        private static List<MapperInfo> DiscoverMappers()
        {
            var result = new List<MapperInfo>();
            var storageMapperType = typeof(IStorageMapper<>);
            var assemblies = AppDomain.CurrentDomain.GetAssemblies();

            foreach (var assembly in assemblies)
            {
                if (assembly.IsDynamic) continue;
                if (IsTestAssembly(assembly)) continue;

                try
                {
                    Type[] types;
                    try
                    {
                        types = assembly.GetTypes();
                    }
                    catch (System.Reflection.ReflectionTypeLoadException ex)
                    {
                        types = ex.Types.Where(t => t != null).ToArray();
                    }

                    foreach (var type in types)
                    {
                        if (type == null || type.IsAbstract || type.IsInterface || type.IsGenericType)
                            continue;

                        var resultType = GetStorageMapperResultType(type, storageMapperType);
                        if (resultType == null) continue;

                        result.Add(new MapperInfo
                        {
                            MapperType = type,
                            ResultType = resultType
                        });
                    }
                }
                catch (Exception ex)
                {
                    Debug.LogWarning($"[StorageMapperScanner] Error scanning {assembly.GetName().Name}: {ex.Message}");
                }
            }

            return result.OrderBy(m => m.MapperType.FullName).ToList();
        }

        private static Type GetStorageMapperResultType(Type type, Type storageMapperType)
        {
            var interfaces = type.GetInterfaces();
            foreach (var iface in interfaces)
            {
                if (iface.IsGenericType && iface.GetGenericTypeDefinition() == storageMapperType)
                {
                    return iface.GetGenericArguments()[0];
                }
            }
            return null;
        }

        private static string GenerateRegistrationCode(List<MapperInfo> mappers)
        {
            var namespaces = new HashSet<string>
            {
                "Core.Abstractions.Services.GameData",
                "Reflex.Core"
            };

            foreach (var m in mappers)
            {
                if (!string.IsNullOrEmpty(m.MapperType.Namespace))
                    namespaces.Add(NormalizeNamespace(m.MapperType.Namespace));
                if (!string.IsNullOrEmpty(m.ResultType.Namespace))
                    namespaces.Add(NormalizeNamespace(m.ResultType.Namespace));
            }

            var sb = new System.Text.StringBuilder();

            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// This file was generated by StorageMapperScanner.");
            sb.AppendLine("// Do not edit manually. Run 'Tools/GameData/Scan and Generate Storage Mapper Registration' to regenerate.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("#pragma warning disable");
            sb.AppendLine();

            foreach (var ns in namespaces.Where(n => !string.IsNullOrEmpty(n)).OrderBy(n => n))
            {
                sb.AppendLine($"using {ns};");
            }

            sb.AppendLine();
            sb.AppendLine($"namespace {Namespace}");
            sb.AppendLine("{");
            sb.AppendLine("    public static class StorageMapperRegistration");
            sb.AppendLine("    {");
            sb.AppendLine("        public static ContainerBuilder RegisterStorageMappers(this ContainerBuilder builder)");
            sb.AppendLine("        {");

            foreach (var m in mappers)
            {
                sb.AppendLine($"            builder.AddSingleton<IStorageMapper<{m.ResultType.Name}>>(_ => new {m.MapperType.Name}());");
            }

            sb.AppendLine();
            sb.AppendLine("            return builder;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static string NormalizeNamespace(string ns)
        {
            if (string.IsNullOrEmpty(ns)) return ns;
            const string prefix = "Source.Runtime.";
            return ns.StartsWith(prefix, StringComparison.Ordinal)
                ? ns.Substring(prefix.Length)
                : ns;
        }

        private static bool WriteIfChanged(string path, string content)
        {
            if (File.Exists(path) && File.ReadAllText(path) == content)
                return false;

            File.WriteAllText(path, content);
            return true;
        }

        private static void EnsureDirectoryExists(string path)
        {
            if (string.IsNullOrEmpty(path)) return;
            if (!Directory.Exists(path))
            {
                Directory.CreateDirectory(path);
            }
        }

        private static bool IsTestAssembly(System.Reflection.Assembly assembly)
        {
            var name = assembly.GetName().Name;
            return name.Contains("Tests") ||
                   name.Contains("Test") ||
                   name.Contains("nunit") ||
                   name.Contains("NSubstitute");
        }

        private class MapperInfo
        {
            public Type MapperType;
            public Type ResultType;
        }
    }
}
#endif
