#if UNITY_EDITOR
using System.Text;

namespace Core.Editor.ElementMappingGenerator
{
    public static class ElementMappingCodeGenerator
    {
        private const string GeneratedNamespace = "Source.Runtime.Core.Presentation.MVVM.Config.Generated";
        private const string GeneratedFolder = "Assets/Source/CodeGen/Elements";
        private const string AssetFolder = "Assets/Source/00. Configs/ElementsMapping";

        public static string GenerateMappingCode(
            string elementTypeName,
            string elementNamespace,
            string dataTypeName,
            string dataNamespace)
        {
            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated>");
            builder.AppendLine("// This file was generated by ElementMappingGenerator.");
            builder.AppendLine("// Do not edit manually.");
            builder.AppendLine("// </auto-generated>");
            builder.AppendLine();
            builder.AppendLine("using Core.Presentation.MVVM.Config;");

            if (!string.IsNullOrEmpty(elementNamespace))
                builder.AppendLine($"using {elementNamespace};");

            if (!string.IsNullOrEmpty(dataNamespace) && dataNamespace != elementNamespace)
                builder.AppendLine($"using {dataNamespace};");

            builder.AppendLine();
            builder.AppendLine($"namespace {GeneratedNamespace}");
            builder.AppendLine("{");
            builder.AppendLine($"    public class {elementTypeName}Mapping : ElementMappingBase<{elementTypeName}, {dataTypeName}>");
            builder.AppendLine("    {");
            builder.AppendLine("    }");
            builder.AppendLine("}");

            return builder.ToString();
        }

        public static string GetMappingClassName(string elementTypeName) =>
            $"{elementTypeName}Mapping";

        public static string GetMappingTypeName(string elementTypeName) =>
            $"{GeneratedNamespace}.{elementTypeName}Mapping";

        public static string GetMappingFilePath(string elementTypeName) =>
            $"{GeneratedFolder}/{elementTypeName}Mapping.cs";

        public static string GetMappingAssetPath(string elementTypeName) =>
            $"{AssetFolder}/{elementTypeName}Mapping.asset";

        public static string GetGeneratedFolder() => GeneratedFolder;

        public static string GetAssetFolder() => AssetFolder;
    }
}
#endif
