#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using UnityEditor.PackageManager;
using UnityEngine;

namespace Core.Editor.CodeGenPipeline
{
    public static class ConsumerCodeGenContext
    {
        public const string OutputDirectory = "Assets/MVVMTemplate.Generated";
        public const string RegistrationPath = OutputDirectory + "/ConsumerRegistration.generated.cs";

        private static readonly Lazy<HashSet<string>> ConsumerAssemblyNames =
            new(BuildConsumerAssemblyNames);

        public static bool IsPackageInstallation =>
            PackageInfo.FindForAssembly(typeof(ConsumerCodeGenContext).Assembly) != null;

        public static string SourceRoot => IsPackageInstallation
            ? Application.dataPath
            : Path.Combine(Application.dataPath, "Source/Runtime");

        public static bool ShouldScanAssembly(Assembly assembly)
        {
            if (assembly == null || assembly.IsDynamic)
                return false;

            return !IsPackageInstallation ||
                   ConsumerAssemblyNames.Value.Contains(assembly.GetName().Name);
        }

        public static bool WriteConsumerPart(
            string partName,
            string generatedRegistration,
            string sourceMethodName,
            string partialMethodName,
            string builderType)
        {
            var part = ConvertToConsumerPart(
                generatedRegistration,
                sourceMethodName,
                partialMethodName,
                builderType);

            Directory.CreateDirectory(OutputDirectory);

            var changed = WriteIfChanged(RegistrationPath, GenerateRegistrationScaffold());
            var partPath = $"{OutputDirectory}/ConsumerRegistration.{partName}.generated.cs";
            return WriteIfChanged(partPath, part) || changed;
        }

        public static string ConvertToConsumerPart(
            string generatedRegistration,
            string sourceMethodName,
            string partialMethodName,
            string builderType)
        {
            if (string.IsNullOrEmpty(generatedRegistration))
                throw new ArgumentException("Generated registration must not be empty.", nameof(generatedRegistration));

            var methodIndex = generatedRegistration.IndexOf(sourceMethodName + "(", StringComparison.Ordinal);
            if (methodIndex < 0)
                throw new InvalidOperationException($"Method '{sourceMethodName}' was not found in generated registration.");

            var openingBrace = generatedRegistration.IndexOf('{', methodIndex);
            var closingBrace = FindMatchingBrace(generatedRegistration, openingBrace);
            var body = generatedRegistration.Substring(openingBrace + 1, closingBrace - openingBrace - 1);
            var bodyLines = body.Replace("\r\n", "\n")
                .Split('\n')
                .Where(line => line.Trim() != "return builder;")
                .ToArray();

            var usings = generatedRegistration.Replace("\r\n", "\n")
                .Split('\n')
                .Where(line => line.StartsWith("using ", StringComparison.Ordinal))
                .Distinct()
                .OrderBy(line => line, StringComparer.Ordinal);

            var result = new StringBuilder();
            result.AppendLine("// <auto-generated>");
            result.AppendLine("// Consumer-owned contribution generated by MVVMTemplate.");
            result.AppendLine("// </auto-generated>");
            result.AppendLine();
            result.AppendLine("#pragma warning disable");
            result.AppendLine();
            foreach (var usingLine in usings)
                result.AppendLine(usingLine);
            result.AppendLine();
            result.AppendLine("namespace MVVMTemplate.Generated");
            result.AppendLine("{");
            result.AppendLine("    public sealed partial class ConsumerRegistration");
            result.AppendLine("    {");
            result.AppendLine($"        partial void {partialMethodName}({builderType} builder)");
            result.AppendLine("        {");
            foreach (var line in bodyLines)
                result.AppendLine(line);
            result.AppendLine("        }");
            result.AppendLine("    }");
            result.AppendLine("}");
            return result.ToString();
        }

        private static string GenerateRegistrationScaffold()
        {
            return "// <auto-generated>\n" +
                   "// Consumer-owned MVVMTemplate composition contribution.\n" +
                   "// </auto-generated>\n\n" +
                   "using Core.DependencyInjection;\n" +
                   "using Core.Mediator.Registration;\n" +
                   "using Reflex.Core;\n" +
                   "using UnityEngine.Scripting;\n\n" +
                   "namespace MVVMTemplate.Generated\n" +
                   "{\n" +
                   "    [Preserve]\n" +
                   "    public sealed partial class ConsumerRegistration : ICoreRegistrationContributor\n" +
                   "    {\n" +
                   "        public void RegisterBindings(ContainerBuilder builder)\n" +
                   "        {\n" +
                   "            RegisterViewModels(builder);\n" +
                   "            RegisterStorageMappers(builder);\n" +
                   "        }\n\n" +
                   "        public void RegisterMediator(MediatorBuilder builder)\n" +
                   "        {\n" +
                   "            RegisterViewHandlers(builder);\n" +
                   "            RegisterMediatorHandlers(builder);\n" +
                   "            RegisterElementHandlers(builder);\n" +
                   "            RegisterToolkitElementHandlers(builder);\n" +
                   "        }\n\n" +
                   "        partial void RegisterViewModels(ContainerBuilder builder);\n" +
                   "        partial void RegisterStorageMappers(ContainerBuilder builder);\n" +
                   "        partial void RegisterViewHandlers(MediatorBuilder builder);\n" +
                   "        partial void RegisterMediatorHandlers(MediatorBuilder builder);\n" +
                   "        partial void RegisterElementHandlers(MediatorBuilder builder);\n" +
                   "        partial void RegisterToolkitElementHandlers(MediatorBuilder builder);\n" +
                   "    }\n" +
                   "}\n";
        }

        private static HashSet<string> BuildConsumerAssemblyNames()
        {
            var result = new HashSet<string>(StringComparer.Ordinal);

            foreach (var assembly in UnityEditor.Compilation.CompilationPipeline.GetAssemblies())
            {
                if (assembly.sourceFiles.Any(IsConsumerSourcePath))
                    result.Add(assembly.name);
            }

            return result;
        }

        private static bool IsConsumerSourcePath(string path)
        {
            if (string.IsNullOrEmpty(path))
                return false;

            var normalized = path.Replace('\\', '/');
            return normalized.StartsWith("Assets/", StringComparison.OrdinalIgnoreCase) &&
                   !normalized.StartsWith(OutputDirectory + "/", StringComparison.OrdinalIgnoreCase);
        }

        private static int FindMatchingBrace(string value, int openingBrace)
        {
            if (openingBrace < 0)
                throw new InvalidOperationException("Generated registration method has no body.");

            var depth = 0;
            for (var i = openingBrace; i < value.Length; i++)
            {
                if (value[i] == '{') depth++;
                if (value[i] != '}') continue;

                depth--;
                if (depth == 0)
                    return i;
            }

            throw new InvalidOperationException("Generated registration method body is not balanced.");
        }

        private static bool WriteIfChanged(string path, string content)
        {
            if (File.Exists(path) && File.ReadAllText(path) == content)
                return false;

            File.WriteAllText(path, content);
            return true;
        }
    }
}
#endif
